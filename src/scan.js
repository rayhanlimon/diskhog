/** Filesystem scan: find reclaimable dev directories with size + age. Zero deps. */
import fs from 'node:fs';
import path from 'node:path';

export const TARGETS = [
  { name: 'node_modules', kind: 'deps', safe: 'reinstallable via npm/ci' },
  { name: 'target', kind: 'build', safe: 'cargo rebuilds it', guard: 'Cargo.toml' },
  { name: '__pycache__', kind: 'cache', safe: 'regenerated by python' },
  { name: '.venv', kind: 'deps', safe: 'recreatable via requirements' },
  { name: 'venv', kind: 'deps', safe: 'recreatable via requirements' },
  { name: '.next', kind: 'build', safe: 'next build regenerates' },
  { name: 'dist', kind: 'build', safe: 'rebuild via build step' },
  { name: 'build', kind: 'build', safe: 'rebuild via build step' },
  { name: 'coverage', kind: 'report', safe: 'regenerated by tests' },
  { name: '.pytest_cache', kind: 'cache', safe: 'regenerated by pytest' },
  { name: '.turbo', kind: 'cache', safe: 'regenerated by turbo' },
  { name: '.parcel-cache', kind: 'cache', safe: 'regenerated by parcel' },
];

const SKIP_DIRS = new Set(['.git', '.hg', '.svn']);

export async function dirSize(dir, { maxEntries = 200000 } = {}) {
  let bytes = 0, files = 0, oldestMtime = Date.now(), newestMtime = 0;
  const stack = [dir];
  let entries = 0;
  while (stack.length) {
    const cur = stack.pop();
    let ents;
    try { ents = await fs.promises.readdir(cur, { withFileTypes: true }); }
    catch { continue; }
    for (const e of ents) {
      if (++entries > maxEntries) return { bytes, files, truncated: true, oldestMtime, newestMtime };
      const full = path.join(cur, e.name);
      if (e.isSymbolicLink()) continue;
      if (e.isDirectory()) { stack.push(full); continue; }
      if (!e.isFile()) continue;
      try {
        const st = await fs.promises.stat(full);
        bytes += st.size; files++;
        if (st.mtimeMs < oldestMtime) oldestMtime = st.mtimeMs;
        if (st.mtimeMs > newestMtime) newestMtime = st.mtimeMs;
      } catch { /* raced delete */ }
    }
  }
  return { bytes, files, truncated: false, oldestMtime, newestMtime };
}

export async function scan(root, { maxDepth = 6, targets = TARGETS } = {}) {
  const hits = [];
  const wanted = new Map(targets.map((t) => [t.name, t]));
  async function walk(dir, depth) {
    let ents;
    try { ents = await fs.promises.readdir(dir, { withFileTypes: true }); }
    catch { return; }
    for (const e of ents) {
      if (!e.isDirectory() || e.isSymbolicLink()) continue;
      if (SKIP_DIRS.has(e.name)) continue;
      const full = path.join(dir, e.name);
      const spec = wanted.get(e.name);
      if (spec) {
        if (spec.guard) {
          try { await fs.promises.stat(path.join(dir, spec.guard)); }
          catch { /* guard missing: still record but flag */ }
        }
        const info = await dirSize(full);
        let projMtime = 0;
        try { projMtime = (await fs.promises.stat(dir)).mtimeMs; } catch {}
        hits.push({ path: full, project: dir, target: spec, ...info, projectMtime: projMtime });
        continue; // do not descend into the junk itself
      }
      if (depth < maxDepth) await walk(full, depth + 1);
    }
  }
  await walk(path.resolve(root), 0);
  return hits.sort((a, b) => b.bytes - a.bytes);
}

export function formatBytes(n) {
  if (n < 1024) return `${n} B`;
  const units = ['KB', 'MB', 'GB', 'TB'];
  let v = n / 1024, u = 0;
  while (v >= 1024 && u < units.length - 1) { v /= 1024; u++; }
  return `${v.toFixed(v >= 100 ? 0 : 1)} ${units[u]}`;
}

export function ageDays(mtimeMs, now = Date.now()) {
  return Math.max(0, Math.floor((now - mtimeMs) / 86400000));
}
